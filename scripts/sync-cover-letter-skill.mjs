import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const source = new URL("docs/writing-skills/write-kirtan-cover-letter/SKILL.md", root);
const target = new URL("src/lib/prompts/kirtan-cover-letter.ts", root);
const text = readFileSync(source, "utf8");
const match = text.match(/<!-- runtime:start -->\s*([\s\S]*?)\s*<!-- runtime:end -->/);
if (!match) throw new Error("Cover-letter runtime markers are missing");
const editorSource = readFileSync(
  new URL("docs/writing-skills/write-kirtan-cover-letter/references/editor.md", root),
  "utf8",
);
const editorMatch = editorSource.match(/<!-- editor:start -->\s*([\s\S]*?)\s*<!-- editor:end -->/);
if (!editorMatch) throw new Error("Cover-letter editor markers are missing");
const contracts = {
  KIRTAN_COVER_LETTER_INSTRUCTIONS: match[1],
  KIRTAN_COVER_LETTER_EDITOR_INSTRUCTIONS: editorMatch[1],
};
const generated =
  "// Generated by scripts/sync-cover-letter-skill.mjs. Edit the skill, then sync.\n" +
  Object.entries(contracts)
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`)
    .join("");
if (process.argv.includes("--check")) {
  const contents = readFileSync(target, "utf8");
  for (const [name, value] of Object.entries(contracts)) {
    const existing = contents.match(
      new RegExp(`export const ${name} =\\s*("(?:[^"\\\\]|\\\\.)*")\\s*;`),
    );
    if (!existing || JSON.parse(existing[1]) !== value)
      throw new Error("Cover-letter runtime is stale; run the sync script");
  }
  console.log("Cover-letter skill and runtime match.");
} else {
  writeFileSync(target, generated);
  console.log("Updated cover-letter runtime from skill.");
}
